import { FEDERATION_PARAGLIDE_OUTDIR } from "../../vite.federation-i18n";
import { FEDERATION_EXCLUDED_NAMESPACES } from "../../vite.i18n";

const CATALOG = [
	"live.a",
	"live.b",
	"live.route.x",
	"live.route.y",
	"network.c",
];
const GENERATED = resolve(
	import.meta.dirname,
	"../../../../packages/i18n/generated",
);

const BARREL = `// GENERATED by packages/i18n/scripts/generate-registry.ts — DO NOT EDIT.
import { "live.a" as _0 } from "../../src/paraglide/messages/live_a.js";
import { "live.b" as _1 } from "../../src/paraglide/messages/live_b.js";

export const messages = {
	["live.a"]: _0,
	["live.b"]: _1,
};
`;

const temporary: string[] = [];
afterEach(() => {
	for (const dir of temporary.splice(0))
		rmSync(dir, { recursive: true, force: true });
});
function scratch(): string {
	const dir = mkdtempSync(join(tmpdir(), "federation-catalog-"));
	temporary.push(dir);
	return dir;
}

describe("referencedCatalogKeys", () => {
	it("collects exact dotted literals and ignores non-keys", () => {
		const code = `m["live.a"](); t('network.c'); const css = "text.sm"; m[\`live.b\`]();`;
		expect([...referencedCatalogKeys(code, CATALOG)].sort()).toEqual([
			"live.a",
			"live.b",
			"network.c",
		]);
	});

	it("expands template and concatenation heads to every key below them", () => {
		expect(
			// biome-ignore lint/suspicious/noTemplateCurlyInString: the fixture is source text holding a template literal
			[...referencedCatalogKeys("t(`live.route.${reason}`)", CATALOG)].sort(),
		).toEqual(["live.route.x", "live.route.y"]);
		expect(
			[...referencedCatalogKeys('t("live.route."+reason)', CATALOG)].sort(),
		).toEqual(["live.route.x", "live.route.y"]);
	});
});

describe("filterNamespaceBarrel", () => {
	it("keeps only the listed keys' imports and entries", () => {
		const filtered = filterNamespaceBarrel(BARREL, new Set(["live.b"]));
		expect(filtered).toContain('import { "live.b" as _1 }');
		expect(filtered).toContain('["live.b"]: _1,');
		expect(filtered).not.toContain("live.a");
	});

	it("empties a barrel none of whose keys are listed", () => {
		expect(filterNamespaceBarrel(BARREL, new Set(["network.c"]))).toBe(
			"export const messages = {};\n",
		);
	});

	it("refuses a barrel line shape it does not recognise", () => {
		const changed = BARREL.replace('\t["live.b"]: _1,', "\t...{ live: _1 },");
		expect(() => filterNamespaceBarrel(changed, new Set(["live.a"]))).toThrow(
			/unrecognised namespace barrel line/,
		);
	});

	it("parses every barrel the i18n generator emits", () => {
		const everything = new Set(readCatalogKeys());
		const barrels = readdirSync(join(GENERATED, "namespaces")).filter((name) =>
			name.endsWith(".js"),
		);
		expect(barrels.length).toBeGreaterThan(30);
		for (const name of barrels) {
			const source = readFileSync(join(GENERATED, "namespaces", name), "utf8");
			expect(filterNamespaceBarrel(source, everything), name).toBe(source);
		}
	});
});

describe("expectedFederationKeys", () => {
	it("adds a producer key only when the bundles read its family", () => {
		expect(
			expectedFederationKeys(
				new Set(["live.route.x"]),
				new Set(["live.route.y", "live.other.z", "hud.route.y"]),
			),
		).toEqual(["live.route.x", "live.route.y"]);
	});

	it("never treats a bare namespace as a family", () => {
		expect(
			expectedFederationKeys(
				new Set(["live.a"]),
				new Set(["live.b", "live.route.x"]),
			),
		).toEqual(["live.a"]);
	});
});

describe("producerVocabulary", () => {
	it("collects the reason keys source descriptors carry over the wire", () => {
		const vocabulary = producerVocabulary(readCatalogKeys());
		expect(vocabulary.has("live.education.reason.pipelineNotOffered")).toBe(
			true,
		);
		expect(
			vocabulary.has("live.education.reason.rawCaptureNotStreamable"),
		).toBe(true);
		expect(vocabulary.has("settings.sources.hdmi")).toBe(true);
	});

	it("ignores test sources", () => {
		const dir = scratch();
		mkdirSync(join(dir, "tests"));
		writeFileSync(join(dir, "real.ts"), 'export const r = "live.a";');
		writeFileSync(join(dir, "only.test.ts"), 'export const t = "live.b";');
		writeFileSync(
			join(dir, "tests/helper.ts"),
			'export const h = "network.c";',
		);
		expect([...producerVocabulary(CATALOG, [dir])]).toEqual(["live.a"]);
	});
	it("judges test directories relative to the source root, not the checkout path", () => {
		const dir = join(scratch(), "tests", "checkout", "src");
		mkdirSync(dir, { recursive: true });
		writeFileSync(join(dir, "real.ts"), 'export const r = "live.a";');
		expect([...producerVocabulary(CATALOG, [dir])]).toEqual(["live.a"]);
	});
});

describe("computedLookups", () => {
	it("reports lookups whose key is computed", () => {
		const source = [
			'resolveMessageKey(["settings", "validateStages", stage].join("."));',
			"t(option.reason);",
			"m[backendView.disabledReasonKey]();",
			"msg[key]();",
			// biome-ignore lint/suspicious/noTemplateCurlyInString: source text holding a template literal
			"t(`${prefix}.label`);",
		].join("\n");
		expect(computedLookups(source)).toEqual([
			"m[backendView.disabledReasonKey]",
			"msg[key]",
			'resolveMessageKey(["settings", "validateStages", stage].join("."))',
			// biome-ignore lint/suspicious/noTemplateCurlyInString: source text holding a template literal
			"t(`${prefix}.label`)",
			"t(option.reason)",
		]);
	});

	it("ignores literal keys, key-headed templates, declarations, members and comments", () => {
		const source = [
			'm["live.a"](); t("live.b"); t(\'live.c\');',
			// biome-ignore lint/suspicious/noTemplateCurlyInString: source text holding a template literal
			"resolveMessageKey(`live.route.${reason}`);",
			"export function resolveMessageKey(key, params) {}",
			"format.t(value); item.m[index];",
			"// t(commented.out)",
			"/* m[blocked] */",
			"<!-- t(markup.comment) -->",
			"t();",
		].join("\n");
		expect(computedLookups(source)).toEqual([]);
	});
});

describe("computedLookups: ways around the literal scan", () => {
	const IMPORT =
		'import { m, resolveMessageKey } from "@ceraui/i18n/svelte";\n';

	it("reports the facade imported under another name or as a namespace", () => {
		expect(
			computedLookups(
				'import { resolveMessageKey as translate } from "@ceraui/i18n/svelte";\ntranslate(key);',
			),
		).toEqual(["alias resolveMessageKey as translate"]);
		expect(
			computedLookups(
				'import * as i18n from "@ceraui/i18n/svelte";\ni18n.t(key);',
			),
		).toEqual(['namespace import * as i18n from "@ceraui/i18n/svelte"']);
	});

	it("reports a local copy under another name and the facade handed to a function", () => {
		expect(
			computedLookups(`${IMPORT}const translate = resolveMessageKey;`),
		).toEqual(["alias resolveMessageKey as translate"]);
		expect(computedLookups(`${IMPORT}label(source, m);`)).toEqual([
			"passes m: label(source, m);",
		]);
	});

	it("accepts a local copy under a lookup name and keeps scanning calls through it", () => {
		expect(
			computedLookups(`${IMPORT}const t = resolveMessageKey;\nt("live.a");`),
		).toEqual([]);
		expect(
			computedLookups(`${IMPORT}const t = resolveMessageKey;\nt(key);`),
		).toEqual(["t(key)"]);
	});

	it("reports optional calls, concatenated literals and templates without a dot-terminated head", () => {
		expect(
			computedLookups(
				[
					"t?.(key);",
					't("settings.validateStages" + "." + stage);',
					// biome-ignore lint/suspicious/noTemplateCurlyInString: source text holding a template literal
					"t(`settings.validateStages${sep}${stage}`);",
				].join("\n"),
			),
		).toEqual([
			't("settings.validateStages" + "." + stage)',
			// biome-ignore lint/suspicious/noTemplateCurlyInString: source text holding a template literal
			"t(`settings.validateStages${sep}${stage}`)",
			"t?.(key)",
		]);
	});

	it("ignores names that are not bound to the facade", () => {
		expect(
			computedLookups(
				"const lerp = (a, b, t) => a + (b - a) * t;\nreturn { t };",
			),
		).toEqual([]);
		expect(
			computedLookups(
				'import type { MessageFn } from "@ceraui/i18n/svelte";\nuse(m);',
			),
		).toEqual([]);
	});
});

describe("committed computed-lookup declarations", () => {
	it("give every lookup a reason and families that exist in the catalog", () => {
		const catalog = readCatalogKeys();
		const declarations = readComputedLookups();
		expect(declarations.length).toBeGreaterThan(0);
		expect(new Set(declarations.map((entry) => entry.site)).size).toBe(
			declarations.length,
		);
		for (const { site, families } of declarations) {
			for (const family of families) {
				expect(
					catalog.some((key) => key.startsWith(`${family}.`)),
					`${site}: ${family}`,
				).toBe(true);
			}
		}
	});
});

describe("committed federation key list", () => {
	const listed = readFederationCatalogKeys();

	it("is sorted, unique and in its generated format", () => {
		expect(listed).toEqual([...new Set(listed)].sort());
		expect(readFileSync(FEDERATION_CATALOG_KEYS_PATH, "utf8")).toBe(
			serializeFederationCatalogKeys(listed),
		);
	});

	it("names only catalog keys, none from a federation-excluded namespace", () => {
		const catalog = new Set(readCatalogKeys());
		expect(listed.filter((key) => !catalog.has(key))).toEqual([]);
		expect(
			listed.filter((key) =>
				FEDERATION_EXCLUDED_NAMESPACES.includes(key.slice(0, key.indexOf("."))),
			),
		).toEqual([]);
	});

	it("carries the producer's wire reasons the Encoder dialog renders by key", () => {
		expect(listed).toContain("live.education.reason.pipelineNotOffered");
		expect(listed).toContain("live.education.reason.rawCaptureNotStreamable");
	});
});

describe("normalizeModulePath", () => {
	it("uses forward slashes and drops Vite queries and virtual prefixes", () => {
		expect(normalizeModulePath("C:\\repo\\a.svelte?svelte&type=style")).toBe(
			"C:/repo/a.svelte",
		);
		expect(normalizeModulePath("\0/repo/b.js")).toBe("/repo/b.js");
	});
});

describe("isCatalogModule", () => {
	it("matches a slash-normalized module id against a backslash output directory", () => {
		expect(
			isCatalogModule("C:/repo/cache/messages/en.js", "C:\\repo\\cache"),
		).toBe(true);
		expect(
			isCatalogModule("C:/repo/src/Dialog.svelte", "C:\\repo\\cache"),
		).toBe(false);
	});

	it("treats the generated facade and both Paraglide outputs as the catalog", () => {
		expect(
			isCatalogModule(
				join(GENERATED, "namespaces/live.js"),
				FEDERATION_PARAGLIDE_OUTDIR,
			),
		).toBe(true);
		expect(
			isCatalogModule(
				join(FEDERATION_PARAGLIDE_OUTDIR, "messages/en.js"),
				FEDERATION_PARAGLIDE_OUTDIR,
			),
		).toBe(true);
		expect(
			isCatalogModule(
				resolve(import.meta.dirname, "../main/dialogs/EncoderDialog.svelte"),
				FEDERATION_PARAGLIDE_OUTDIR,
			),
		).toBe(false);
	});
});

describe("federationCatalogPlugin", () => {
	const DIALOG = resolve(import.meta.dirname, "../main/dialogs/Example.svelte");

	function run(
		keys: string[],
		code: string,
		mode?: string,
		lookups: { site: string; families: string[]; why: string }[] = [],
		source?: string,
	) {
		const dir = scratch();
		const keysPath = join(dir, "catalog-keys.json");
		const computedLookupsPath = join(dir, "computed-lookups.json");
		writeFileSync(keysPath, serializeFederationCatalogKeys(keys));
		writeFileSync(computedLookupsPath, JSON.stringify({ lookups }));
		const sourcePath = join(dir, "Dialog.svelte");
		if (source !== undefined) writeFileSync(sourcePath, source);
		const plugin = federationCatalogPlugin({
			paraglideOutdir: FEDERATION_PARAGLIDE_OUTDIR,
			keysPath,
			computedLookupsPath,
			root: dir,
			mode,
		});
		plugin.buildStart();
		const warnings: string[] = [];
		const context = {
			error(message: string): never {
				throw new Error(message);
			},
			warn(message: string) {
				warnings.push(message);
			},
		};
		const bundle = {
			"toast-host.js": {
				type: "chunk" as const,
				modules: {
					[source === undefined ? DIALOG : sourcePath]: { code },
					[join(GENERATED, "namespaces/network.js")]: {
						code: '"network.os.deviceBusy"',
					},
				},
			},
		};
		plugin.generateBundle.call(context, {}, bundle);
		return { keysPath, warnings, plugin };
	}

	const expectedFor = (code: string) =>
		expectedFederationKeys(
			referencedCatalogKeys(code, readCatalogKeys()),
			producerVocabulary(readCatalogKeys()),
		);

	it("passes when the list matches the bundled references", () => {
		const code = 'm["validation.invalid"]()';
		expect(() => run(expectedFor(code), code)).not.toThrow();
	});

	it("fails the build on a key the bundles name but the list lacks", () => {
		const code = 'm["validation.invalid"]()';
		const keys = expectedFor(code).filter(
			(key) => key !== "validation.invalid",
		);
		expect(() => run(keys, code)).toThrow(/missing: validation\.invalid/);
	});

	it("fails the build on a listed key nothing names", () => {
		const code = 'm["validation.invalid"]()';
		expect(() => run([...expectedFor(code), "dialogs.cancel"], code)).toThrow(
			/nothing names any more: dialogs\.cancel/,
		);
	});

	it("ignores literals inside catalog modules", () => {
		const code = 'm["validation.invalid"]()';
		expect(expectedFor(code)).not.toContain("network.os.deviceBusy");
		expect(() => run(expectedFor(code), code)).not.toThrow();
	});

	it("rewrites the list in write mode instead of failing", () => {
		const code = 'm["validation.invalid"]()';
		const { keysPath, warnings } = run([], code, "write");
		expect(readFederationCatalogKeys(keysPath)).toEqual(expectedFor(code));
		expect(warnings.join("\n")).toMatch(/rewrote .*rebuild to ship it/);
	});

	it("narrows namespace barrels on load and leaves other modules alone", () => {
		const code = 'm["validation.invalid"]()';
		const { plugin } = run(expectedFor(code), code);
		plugin.buildStart();
		expect(plugin.load(join(GENERATED, "namespaces/wifiBands.js"))).toBe(
			"export const messages = {};\n",
		);
		expect(plugin.load(DIALOG)).toBeNull();
	});

	it("fails on an undeclared computed lookup, in write mode too", () => {
		const code = 'm["validation.invalid"]()';
		const source =
			'resolveMessageKey(["settings", "validateStages", stage].join("."));';
		for (const mode of [undefined, "write"]) {
			expect(() => run(expectedFor(code), code, mode, [], source)).toThrow(
				/Declare, with the key families each can produce: Dialog\.svelte resolveMessageKey/,
			);
		}
	});

	it("ships every key of a declared lookup's families", () => {
		const code = 'm["validation.invalid"]()';
		const site = "Dialog.svelte t(stageKey)";
		const stages = readCatalogKeys().filter((key) =>
			key.startsWith("settings.validateStages."),
		);
		const keys = [...new Set([...expectedFor(code), ...stages])].sort();
		const lookups = [
			{ site, families: ["settings.validateStages"], why: "test" },
		];
		expect(() =>
			run(keys, code, undefined, lookups, "t(stageKey);"),
		).not.toThrow();
		expect(() =>
			run(expectedFor(code), code, undefined, lookups, "t(stageKey);"),
		).toThrow(/missing: settings\.validateStages\./);
	});

	it("fails on a declaration no bundled code has any more", () => {
		const code = 'm["validation.invalid"]()';
		const lookups = [
			{ site: "Dialog.svelte t(gone)", families: [], why: "test" },
		];
		expect(() => run(expectedFor(code), code, undefined, lookups, "")).toThrow(
			/Remove declarations no bundled code has: Dialog\.svelte t\(gone\)/,
		);
	});

	it("is registered in the real federation build config after the namespace exclusion", () => {
		const names = (
			(federationConfig.plugins ?? []).flat(Number.POSITIVE_INFINITY) as {
				name?: unknown;
			}[]
		).map((plugin) => String(plugin?.name ?? ""));
		const catalog = names.indexOf("ceraui:federation-catalog");
		expect(catalog).toBeGreaterThan(
			names.indexOf("ceraui:federation-excluded-i18n-namespaces"),
		);
	});
});
