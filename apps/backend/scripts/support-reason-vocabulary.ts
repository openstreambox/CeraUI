/** Build the closed vocabulary of modem error text for the support download.
 *
 * ModemManager and NetworkManager put an error's message after "couldn't …:"
 * and "failed to connect modem:". The export keeps that text only when every
 * colon-separated segment is one of ModemManager's own fixed error phrases;
 * anything else becomes [reason]. The phrases come from the Debian source
 * packages of the versions devices run (bookworm 1.20.4; CeraLive's 1.24.2
 * carry on trixie), passed as extracted source directories:
 *
 *   bun scripts/support-reason-vocabulary.ts --write \
 *     <modemmanager-1.20.4 dir> <modemmanager-1.24.2 dir>
 */
import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const GENERATED_PATH = join(
	import.meta.dir,
	"../src/modules/system/support-reason-vocabulary.generated.ts",
);

const ERROR_CALL =
	/\b(?:g_set_error(?:_literal)?|g_error_new(?:_literal)?|g_task_return_new_error(?:_literal)?|g_prefix_error(?:_literal)?|g_propagate_prefixed_error)\s*\(/g;
const LOG_CALL = /\bmm_obj_(?:info|msg|warn|err)\s*\(/g;

function cFiles(dir: string): string[] {
	const out: string[] = [];
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) out.push(...cFiles(path));
		else if (entry.name.endsWith(".c")) out.push(path);
	}
	return out;
}

function unescapeC(text: string): string {
	return text.replace(/\\(["'\\])/g, "$1");
}

/** First string-literal run in each call's arguments (C concatenation). */
function callFormats(text: string, call: RegExp): string[] {
	const out: string[] = [];
	for (const match of text.matchAll(call)) {
		let i = (match.index ?? 0) + match[0].length;
		let depth = 1;
		const start = i;
		while (i < text.length && depth) {
			const c = text[i];
			if (c === '"') {
				i++;
				while (i < text.length && text[i] !== '"')
					i += text[i] === "\\" ? 2 : 1;
			} else if (c === "(") depth++;
			else if (c === ")") depth--;
			i++;
		}
		const args = text.slice(start, i - 1);
		const run = /((?:"(?:[^"\\]|\\.)*"\s*)+)/.exec(args);
		if (!run?.[1]) continue;
		out.push(
			[...run[1].matchAll(/"((?:[^"\\]|\\.)*)"/g)]
				.map((m) => unescapeC(m[1] ?? ""))
				.join(""),
		);
	}
	return out;
}

/** `[MM_..._ERROR_X] = "Text"` rows of the error description tables. */
function tableStrings(text: string): string[] {
	return [...text.matchAll(/\[MM_[A-Z0-9_]+\]\s*=\s*"((?:[^"\\]|\\.)*)"/g)].map(
		(m) => unescapeC(m[1] ?? ""),
	);
}

function phrase(text: string): string | undefined {
	const value = text.trim();
	if (value.length < 3 || value.length > 120) return undefined;
	if (/[%\n\t]/.test(value) || !/[A-Za-z]{3}/.test(value)) return undefined;
	return value;
}

export function collectVocabulary(roots: readonly string[]): {
	phrases: string[];
	couldnt: string[];
} {
	const phrases = new Set<string>();
	const couldnt = new Set<string>();
	for (const root of roots)
		for (const file of cFiles(root)) {
			const text = readFileSync(file, "utf8");
			for (const value of tableStrings(text)) {
				const kept = phrase(value);
				if (kept) phrases.add(kept);
			}
			for (const format of callFormats(text, ERROR_CALL)) {
				// "Couldn't X: %s" contributes "Couldn't X"; a fixed message
				// contributes each of its segments.
				const head = format.replace(/:\s*%s\s*$/, "");
				for (const segment of head.split(": ")) {
					const kept = phrase(segment);
					if (kept) phrases.add(kept);
					if (segment.includes("%")) break;
				}
			}
			for (const format of callFormats(text, LOG_CALL)) {
				const head = /^couldn't ([a-z0-9 '-]{3,60}?)(?:: %s)?$/.exec(format);
				if (head?.[1]) couldnt.add(head[1]);
			}
		}
	return {
		phrases: [...phrases].sort(),
		couldnt: [...couldnt].sort(),
	};
}

export function renderGenerated(vocabulary: {
	phrases: readonly string[];
	couldnt: readonly string[];
}): string {
	return `// Generated by apps/backend/scripts/support-reason-vocabulary.ts from the
// ModemManager 1.20.4 and 1.24.2 sources; do not edit.

/** ModemManager's fixed error phrases (one colon-separated segment each). */
export const MODEM_ERROR_PHRASES: readonly string[] = ${JSON.stringify(vocabulary.phrases)};

/** What follows "couldn't" in ModemManager's own warnings. */
export const MODEM_COULDNT_HEADS: readonly string[] = ${JSON.stringify(vocabulary.couldnt)};
`;
}

if (import.meta.main) {
	const roots = process.argv.slice(2).filter((arg) => !arg.startsWith("--"));
	if (roots.length === 0) {
		console.error("usage: support-reason-vocabulary.ts [--write] <mm-src>...");
		process.exit(2);
	}
	const text = renderGenerated(collectVocabulary(roots));
	if (process.argv.includes("--write")) {
		writeFileSync(GENERATED_PATH, text);
		// Match the repository formatting so `biome check` stays clean.
		spawnSync("bunx", ["biome", "format", "--write", GENERATED_PATH], {
			stdio: "inherit",
		});
	} else process.stdout.write(text);
}
